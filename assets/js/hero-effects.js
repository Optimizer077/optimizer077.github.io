/* Portrait effects: the same 30 processes as the GPU background (bg-scenes.js), played on the pixel
   portrait (pixel-hero.js). Each entry is
     w     relative durations [out, hold, back]
     prep  (E)               optional, runs when the effect starts (paths, random destinations)
     at    (q, u, ui, E, o)  writes the tile's position o.x, o.y and optionally its colour o.c
   where q is one tile (q.tx, q.ty: where it belongs; q.colours, q.heat, q.klev: precomputed colour
   levels), u is the effect's progress 0..1 and ui the same with a per-tile stagger. Every effect is
   a pure function of progress, so playing "back" simply scrubs the same motion in reverse.
   E carries W, H (canvas size in CSS px), cell, LEVELS, HEAT_SNAPS, particles, t (seconds since the
   start), col (dye colours as [r,g,b]) and mixLevels(q, rgb). Captions and formulas live in
   processes.js (generated by build_math.py). */
(function () {
  'use strict';
  var FX = {};
  window.HERO_FX = FX;

  var TAU = Math.PI * 2;

  /* ---------------- helpers ---------------- */
  function pathAt(q, ui, steps, o) {                 // piecewise-linear lookup along a precomputed path
    var f = ui * (steps - 1), k0 = Math.floor(f), k1 = Math.min(steps - 1, k0 + 1), w = f - k0, P = q.path;
    o.x = P[k0 * 2] + (P[k1 * 2] - P[k0 * 2]) * w;
    o.y = P[k0 * 2 + 1] + (P[k1 * 2 + 1] - P[k0 * 2 + 1]) * w;
  }
  function eachPath(E, steps, fill) {                // allocate a path per tile and let fill(q, path) write it
    var P = E.particles;
    for (var i = 0; i < P.length; i++) { P[i].path = new Float32Array(steps * 2); fill(P[i], P[i].path, i); }
  }
  function toX(E, nx) { return (nx + 1) / 2 * E.W; }       // normalised [-1,1] (y up) -> canvas px
  function toY(E, ny) { return (1 - ny) / 2 * E.H; }
  function nxOf(E, q) { return q.tx / E.W * 2 - 1; }
  function nyOf(E, q) { return 1 - q.ty / E.H * 2; }
  function clamp(x, a, b) { return x < a ? a : x > b ? b : x; }
  function lerpTo(q, ui, o) { o.x = q.tx + (q.ax - q.tx) * ui; o.y = q.ty + (q.ay - q.ty) * ui; }
  function byLuminance(P) {                           // tile indices, darkest first
    return P.map(function (q, i) { return i; }).sort(function (a, b) { return P[a].lum - P[b].lum; });
  }
  function reflect(x, lo, hi) {                       // fold x back into [lo, hi]
    var L = hi - lo, m = (x - lo) % (2 * L);
    if (m < 0) m += 2 * L;
    return lo + (m > L ? 2 * L - m : m);
  }
  function gaussian() { return Math.sqrt(-2 * Math.log(Math.max(Math.random(), 1e-9))) * Math.cos(TAU * Math.random()); }

  /* ====================================================================================
     1-10: the original effects
     ==================================================================================== */

  FX.diffusion = {
    w: [1700, 500, 2600],
    prep: function (E) {
      E.particles.forEach(function (q) { q.nx = Math.random() * (E.W - E.cell); q.ny = Math.random() * (E.H - E.cell); });
    },
    at: function (q, u, ui, E, o) {
      var jit = ui * E.cell * 2.4;
      o.x = q.tx + (q.nx - q.tx) * ui + (Math.random() - 0.5) * jit;
      o.y = q.ty + (q.ny - q.ty) * ui + (Math.random() - 0.5) * jit;
      o.c = q.colours[Math.round((1 - ui) * (E.LEVELS - 1))];
    }
  };

  var FLOW_STEPS = 24;
  function curl(x, y, t) {                            // same stream function as the background
    var qx = x * 1.6, qy = y * 1.6;
    var a = 1.3 * qx + 0.21 * t, b = 1.1 * qy - 0.17 * t, c = 2.1 * (qx + qy) + 0.11 * t, d = 3.7 * qx - 2.9 * qy + 0.3 * t;
    var dx = 1.3 * Math.cos(a) * Math.cos(b) + 1.05 * Math.cos(c) + 0.925 * Math.cos(d);
    var dy = -1.1 * Math.sin(a) * Math.sin(b) + 1.05 * Math.cos(c) - 0.725 * Math.cos(d);
    return [dy, -dx];
  }
  FX.flow = {
    w: [2200, 300, 2400],
    prep: function (E) {
      var t0 = Math.random() * 100, stepLen = E.W * 0.028;
      eachPath(E, FLOW_STEPS, function (q, path) {
        var px = q.tx, py = q.ty;
        for (var s = 0; s < FLOW_STEPS; s++) {
          path[s * 2] = px; path[s * 2 + 1] = py;
          var v = curl(px / E.W * 2 - 1, 1 - py / E.H * 2, t0 + s * 0.05);
          var len = Math.sqrt(v[0] * v[0] + v[1] * v[1]) + 1e-6;
          px += v[0] / len * stepLen;
          py -= v[1] / len * stepLen;
        }
      });
    },
    at: function (q, u, ui, E, o) { pathAt(q, ui, FLOW_STEPS, o); }
  };

  FX.heat = {
    w: [2000, 600, 2200],
    at: function (q, u, ui, E, o) { o.c = q.heat[Math.round(u * (E.HEAT_SNAPS.length - 1))]; }   // the whole image diffuses together
  };

  function attractorPlace(E, pts, mapX, mapY) {
    for (var i = pts.length - 1; i > 0; i--) { var j = Math.floor(Math.random() * (i + 1)); var t = pts[i]; pts[i] = pts[j]; pts[j] = t; }
    E.particles.forEach(function (q, i) { q.ax = mapX(pts[i]); q.ay = mapY(pts[i]); });
  }
  function lorenzPoints(n) {
    var x = 0.1, y = 0, z = 25, pts = [], dt = 0.006;
    for (var i = 0; i < 400; i++) { var dx0 = 10 * (y - x), dy0 = x * (28 - z) - y, dz0 = x * y - 8 / 3 * z; x += dx0 * dt; y += dy0 * dt; z += dz0 * dt; }
    for (var k = 0; k < n; k++) {
      for (var s = 0; s < 3; s++) { var dx = 10 * (y - x), dy = x * (28 - z) - y, dz = x * y - 8 / 3 * z; x += dx * dt; y += dy * dt; z += dz * dt; }
      pts.push([x, z]);
    }
    return pts;
  }
  function bendAt(q, ui, E, o) {                      // fly to the attractor on a slight curve
    var bend = Math.sin(Math.PI * ui) * E.cell * 5;
    o.x = q.tx + (q.ax - q.tx) * ui + bend;
    o.y = q.ty + (q.ay - q.ty) * ui - bend * 0.6;
  }
  FX.lorenz = {
    w: [2200, 700, 2600],
    prep: function (E) {
      attractorPlace(E, lorenzPoints(E.particles.length),
        function (p) { return E.W / 2 + p[0] / 22 * E.W * 0.46 - E.cell / 2; },
        function (p) { return E.H * 0.92 - p[1] / 50 * E.H * 0.84; });
    },
    at: function (q, u, ui, E, o) { bendAt(q, ui, E, o); }
  };

  FX.flowmatch = {
    w: [1800, 500, 1800],
    stagger: false,                                   // every tile moves in lock-step along a straight line
    prep: function (E) {
      E.particles.forEach(function (q) { q.nx = Math.random() * (E.W - E.cell); q.ny = Math.random() * (E.H - E.cell); });
    },
    at: function (q, u, ui, E, o) {
      o.x = q.tx + (q.nx - q.tx) * ui;
      o.y = q.ty + (q.ny - q.ty) * ui;
      o.c = q.colours[Math.round((1 - ui) * (E.LEVELS - 1))];
    }
  };

  var LANGEVIN_STEPS = 28;
  var WELLS = [[-0.55, 0.45], [0.5, 0.5], [0, -0.1], [-0.45, -0.6], [0.55, -0.55]];   // minima, in [-1, 1]²
  function lossGrad(x, y) {                           // U(p) = 0.12|p|² − Σ exp(−|p − wᵢ|² / 0.06)
    var gx = 0.24 * x, gy = 0.24 * y;
    for (var i = 0; i < WELLS.length; i++) {
      var dx = x - WELLS[i][0], dy = y - WELLS[i][1], e = Math.exp(-(dx * dx + dy * dy) / 0.06);
      gx += e * 2 * dx / 0.06; gy += e * 2 * dy / 0.06;
    }
    return [gx, gy];
  }
  FX.langevin = {
    w: [2400, 500, 2200],
    prep: function (E) {
      eachPath(E, LANGEVIN_STEPS, function (q, path) {
        var x = q.tx / E.W * 2 - 1, y = q.ty / E.H * 2 - 1;
        for (var s = 0; s < LANGEVIN_STEPS; s++) {
          path[s * 2] = (x + 1) / 2 * E.W; path[s * 2 + 1] = (y + 1) / 2 * E.H;
          var g = lossGrad(x, y);
          x += -g[0] * 0.012 + (Math.random() - 0.5) * 0.012;      // gradient step + Langevin noise
          y += -g[1] * 0.012 + (Math.random() - 0.5) * 0.012;
        }
      });
    },
    at: function (q, u, ui, E, o) { pathAt(q, ui, LANGEVIN_STEPS, o); }
  };

  FX.wave = {
    w: [1400, 1800, 1400],
    at: function (q, u, ui, E, o) {                   // two damped circular waves; u scales the amplitude
      var W = E.W, H = E.H, tt = E.t;
      var cx1 = W * 0.3, cy1 = H * 0.35, cx2 = W * 0.72, cy2 = H * 0.7;
      var dx1 = q.tx - cx1, dy1 = q.ty - cy1, r1 = Math.sqrt(dx1 * dx1 + dy1 * dy1) + 1e-3;
      var dx2 = q.tx - cx2, dy2 = q.ty - cy2, r2 = Math.sqrt(dx2 * dx2 + dy2 * dy2) + 1e-3;
      var a1 = Math.sin(r1 * 0.09 - tt * 7) * Math.exp(-r1 / W * 1.2);
      var a2 = Math.sin(r2 * 0.09 - tt * 7 + 1.5) * Math.exp(-r2 / W * 1.2);
      var amp = u * E.cell * 2.6;
      o.x = q.tx + (dx1 / r1 * a1 + dx2 / r2 * a2) * amp;
      o.y = q.ty + (dy1 / r1 * a1 + dy2 / r2 * a2) * amp;
    }
  };

  FX.vortex = {
    w: [2000, 600, 2200],
    at: function (q, u, ui, E, o) {                   // Gaussian vortex: the twist falls off with distance from the core
      var vx0 = q.tx - E.W / 2, vy0 = q.ty - E.H / 2, R0 = E.W * 0.36;
      var ang = ui * 5.5 * Math.exp(-(vx0 * vx0 + vy0 * vy0) / (R0 * R0));
      var ca = Math.cos(ang), sa = Math.sin(ang);
      o.x = E.W / 2 + vx0 * ca - vy0 * sa;
      o.y = E.H / 2 + vx0 * sa + vy0 * ca;
    }
  };

  FX.gravity = {
    w: [2000, 900, 2000],
    at: function (q, u, ui, E, o) {                   // point-mass lens: an image at radius b appears at (b + sqrt(b² + 4 θE²)) / 2
      var lx = q.tx - E.W * 0.5, ly = q.ty - E.H * 0.42, b = Math.sqrt(lx * lx + ly * ly) + 1e-3;
      var thE = E.W * 0.2, rl = (b + Math.sqrt(b * b + 4 * thE * thE)) / 2;
      var rr = b + (rl - b) * ui;
      o.x = E.W * 0.5 + lx / b * rr;
      o.y = E.H * 0.42 + ly / b * rr;
    }
  };

  FX.kmeans = {
    w: [1800, 1000, 1800],
    at: function (q, u, ui, E, o) {
      o.c = q.klev[Math.round(ui * 5)];
      o.x = q.tx + (q.kx - q.tx) * ui * 0.35;
      o.y = q.ty + (q.ky - q.ty) * ui * 0.35;
    }
  };

  /* ====================================================================================
     11-30: new effects
     ==================================================================================== */

  // Rössler: x' = -y - z, y' = x + ay, z' = b + z(x - c)
  FX.rossler = {
    w: [2200, 700, 2600],
    prep: function (E) {
      var x = 1, y = 1, z = 1, pts = [], dt = 0.04, i, k;
      var step = function () { var dx = -y - z, dy = x + 0.2 * y, dz = 0.2 + z * (x - 5.7); x += dx * dt; y += dy * dt; z += dz * dt; };
      for (i = 0; i < 800; i++) step();
      for (k = 0; k < E.particles.length; k++) { step(); step(); step(); pts.push([x, y]); }
      var s = Math.min(E.W, E.H) / 25;
      attractorPlace(E, pts,
        function (p) { return E.W / 2 + (p[0] - 1) * s * 1.15 - E.cell / 2; },
        function (p) { return E.H / 2 - (p[1] + 1) * s * 1.15; });
    },
    at: function (q, u, ui, E, o) { bendAt(q, ui, E, o); }
  };

  // Clifford map: x' = sin(ay) + c cos(ax), y' = sin(bx) + d cos(by); each tile follows its own orbit
  var CLIFF_STEPS = 10;
  FX.clifford = {
    w: [2200, 600, 2400],
    prep: function (E) {
      var a = -1.4, b = 1.6, c = 1, d = 0.7;
      eachPath(E, CLIFF_STEPS, function (q, path) {
        var x = nxOf(E, q) * 1.8, y = nyOf(E, q) * 1.8;
        path[0] = q.tx; path[1] = q.ty;
        for (var s = 1; s < CLIFF_STEPS; s++) {
          var nx = Math.sin(a * y) + c * Math.cos(a * x), ny = Math.sin(b * x) + d * Math.cos(b * y);
          x = nx; y = ny;
          path[s * 2] = toX(E, x / 2.5) - E.cell / 2; path[s * 2 + 1] = toY(E, y / 2.5) - E.cell / 2;
        }
      });
    },
    at: function (q, u, ui, E, o) { pathAt(q, ui, CLIFF_STEPS, o); }
  };

  // Double pendulum: every tile starts from a slightly different angle pair and follows the tip's displacement
  var DP_STEPS = 18;
  function pend(t1, t2, w1, w2, out) {
    var dl = t1 - t2, den = 3 - Math.cos(2 * dl), G = 9.81;
    out[0] = (-3 * G * Math.sin(t1) - G * Math.sin(t1 - 2 * t2) - 2 * Math.sin(dl) * (w2 * w2 + w1 * w1 * Math.cos(dl))) / den;
    out[1] = (2 * Math.sin(dl) * (2 * w1 * w1 + 2 * G * Math.cos(t1) + w2 * w2 * Math.cos(dl))) / den;
  }
  FX.doublependulum = {
    w: [2600, 600, 2800],
    prep: function (E) {
      var S = Math.min(E.W, E.H) * 0.42, dt = 0.09, a = [0, 0], b = [0, 0], c = [0, 0], d = [0, 0];
      var CS = 2, cols = Math.round(E.W / E.cell), rows = Math.round(E.H / E.cell);
      var gc = Math.ceil(cols / CS) + 1, gr = Math.ceil(rows / CS) + 1;
      var disp = new Float32Array(gc * gr * DP_STEPS * 2);          // tip displacement per step, on the coarse grid
      for (var gy = 0; gy < gr; gy++) {
        for (var gx = 0; gx < gc; gx++) {
          var t1 = 2.1 + 0.5 * (gx * CS / cols * 2 - 1), t2 = 2.5 + 0.5 * (1 - gy * CS / rows * 2), w1 = 0, w2 = 0;
          var x0 = Math.sin(t1) + Math.sin(t2), y0 = -(Math.cos(t1) + Math.cos(t2)), at = (gy * gc + gx) * DP_STEPS * 2;
          for (var s = 0; s < DP_STEPS; s++) {
            disp[at + s * 2] = S * (Math.sin(t1) + Math.sin(t2) - x0);
            disp[at + s * 2 + 1] = -S * (-(Math.cos(t1) + Math.cos(t2)) - y0);
            for (var k = 0; k < 4; k++) {              // RK4 on (theta1, theta2, omega1, omega2)
              pend(t1, t2, w1, w2, a);
              pend(t1 + 0.5 * dt * w1, t2 + 0.5 * dt * w2, w1 + 0.5 * dt * a[0], w2 + 0.5 * dt * a[1], b);
              pend(t1 + 0.5 * dt * (w1 + 0.5 * dt * a[0]), t2 + 0.5 * dt * (w2 + 0.5 * dt * a[1]), w1 + 0.5 * dt * b[0], w2 + 0.5 * dt * b[1], c);
              pend(t1 + dt * (w1 + 0.5 * dt * b[0]), t2 + dt * (w2 + 0.5 * dt * b[1]), w1 + dt * c[0], w2 + dt * c[1], d);
              t1 += dt * (w1 + dt / 6 * (a[0] + b[0] + c[0]));
              t2 += dt * (w2 + dt / 6 * (a[1] + b[1] + c[1]));
              w1 += dt / 6 * (a[0] + 2 * b[0] + 2 * c[0] + d[0]);
              w2 += dt / 6 * (a[1] + 2 * b[1] + 2 * c[1] + d[1]);
            }
          }
        }
      }
      eachPath(E, DP_STEPS, function (q, path) {                    // bilinear blend of the four surrounding grid pendulums
        var fx = q.tx / E.cell / CS, fy = q.ty / E.cell / CS, ix = Math.min(gc - 2, Math.floor(fx)), iy = Math.min(gr - 2, Math.floor(fy));
        var wx = fx - ix, wy = fy - iy, o00 = (iy * gc + ix) * DP_STEPS * 2, o10 = o00 + DP_STEPS * 2, o01 = o00 + gc * DP_STEPS * 2, o11 = o01 + DP_STEPS * 2;
        for (var s = 0; s < DP_STEPS * 2; s++) {
          path[s] = (s % 2 ? q.ty : q.tx) + (1 - wy) * ((1 - wx) * disp[o00 + s] + wx * disp[o10 + s]) + wy * ((1 - wx) * disp[o01 + s] + wx * disp[o11 + s]);
        }
      });
    },
    at: function (q, u, ui, E, o) { pathAt(q, ui, DP_STEPS, o); }
  };

  // Double gyre: psi = A sin(pi f(x,t)) sin(pi y) on [0,2] x [0,1]
  var GYRE_STEPS = 24;
  FX.doublegyre = {
    w: [2600, 500, 2600],
    prep: function (E) {
      var A = 0.28, eps = 0.25, om = 1.1, dt = 0.16;
      var vel = function (x, y, t) {
        var e = eps * Math.sin(om * t), f = e * x * x + (1 - 2 * e) * x, df = 2 * e * x + 1 - 2 * e;
        return [-Math.PI * A * Math.sin(Math.PI * f) * Math.cos(Math.PI * y), Math.PI * A * Math.cos(Math.PI * f) * Math.sin(Math.PI * y) * df];
      };
      eachPath(E, GYRE_STEPS, function (q, path) {
        var x = q.tx / E.W * 2, y = 1 - q.ty / E.H, t = 0;
        for (var s = 0; s < GYRE_STEPS; s++) {
          path[s * 2] = x / 2 * E.W; path[s * 2 + 1] = (1 - y) * E.H;
          var k1 = vel(x, y, t), k2 = vel(x + 0.5 * dt * k1[0], y + 0.5 * dt * k1[1], t + 0.5 * dt);
          x = reflect(x + dt * k2[0], 0, 2); y = reflect(y + dt * k2[1], 0, 1); t += dt;
        }
      });
    },
    at: function (q, u, ui, E, o) { pathAt(q, ui, GYRE_STEPS, o); }
  };

  // Van der Pol: x'' - mu(1 - x²)x' + x = 0, drawn in the (x, x') phase plane
  var VDP_STEPS = 26;
  FX.vanderpol = {
    w: [2400, 700, 2400],
    prep: function (E) {
      var mu = 1.5, dt = 0.07;
      eachPath(E, VDP_STEPS, function (q, path) {
        var x = nxOf(E, q) * 3.6, v = nyOf(E, q) * 5;
        for (var s = 0; s < VDP_STEPS; s++) {
          path[s * 2] = s === 0 ? q.tx : (x / 4.4 + 1) / 2 * E.W;
          path[s * 2 + 1] = s === 0 ? q.ty : (1 - v / 5.6) / 2 * E.H;
          for (var k = 0; k < 3; k++) { var a = v, b = mu * (1 - x * x) * v - x; x += a * dt; v += b * dt; }
        }
      });
    },
    at: function (q, u, ui, E, o) { pathAt(q, ui, VDP_STEPS, o); }
  };

  // Chaos game: halfway jumps toward random vertices of a triangle build the Sierpinski gasket
  var CG_STEPS = 9;
  FX.chaosgame = {
    w: [2300, 600, 2300],
    prep: function (E) {
      var V = [[E.W / 2, E.H * 0.04], [E.W * 0.03, E.H * 0.96], [E.W * 0.97, E.H * 0.96]];
      eachPath(E, CG_STEPS, function (q, path) {
        var x = q.tx, y = q.ty;
        for (var s = 0; s < CG_STEPS; s++) {
          path[s * 2] = x; path[s * 2 + 1] = y;
          var v = V[Math.floor(Math.random() * 3)];
          x = (x + v[0]) / 2; y = (y + v[1]) / 2;
        }
      });
    },
    at: function (q, u, ui, E, o) { pathAt(q, ui, CG_STEPS, o); }
  };

  // Lévy flight: short steps with rare power-law jumps (alpha = 1.4)
  var LEVY_STEPS = 14;
  FX.levy = {
    w: [2300, 600, 2300],
    prep: function (E) {
      eachPath(E, LEVY_STEPS, function (q, path) {
        var x = q.tx, y = q.ty;
        for (var s = 0; s < LEVY_STEPS; s++) {
          path[s * 2] = x; path[s * 2 + 1] = y;
          var len = Math.min(0.006 * Math.pow(Math.max(Math.random(), 1e-3), -1 / 1.4), 1.3) * E.W, a = Math.random() * TAU;
          x = reflect(x + Math.cos(a) * len + gaussian() * E.cell * 0.4, 0, E.W - E.cell);
          y = reflect(y + Math.sin(a) * len + gaussian() * E.cell * 0.4, 0, E.H - E.cell);
        }
      });
    },
    at: function (q, u, ui, E, o) { pathAt(q, ui, LEVY_STEPS, o); }
  };

  // MCMC: tempered Metropolis walk into a banana-shaped density
  var MC_STEPS = 20;
  function logBanana(x, y, beta) {
    var d = y + 0.9 * x * x - 0.35;
    return beta * (-x * x / (2 * 0.42 * 0.42) - d * d / (2 * 0.07 * 0.07));
  }
  FX.mcmc = {
    w: [2600, 700, 2400],
    prep: function (E) {
      eachPath(E, MC_STEPS, function (q, path) {
        var x = nxOf(E, q), y = nyOf(E, q);
        for (var s = 0; s < MC_STEPS; s++) {
          path[s * 2] = s === 0 ? q.tx : toX(E, x) - E.cell / 2; path[s * 2 + 1] = s === 0 ? q.ty : toY(E, y) - E.cell / 2;
          var beta = 0.12 + 0.88 * s / (MC_STEPS - 1);
          for (var k = 0; k < 3; k++) {
            var px = x + gaussian() * 0.19, py = y + gaussian() * 0.19;
            if (Math.log(Math.max(Math.random(), 1e-9)) < logBanana(px, py, beta) - logBanana(x, y, beta)) { x = px; y = py; }
          }
        }
      });
    },
    at: function (q, u, ui, E, o) { pathAt(q, ui, MC_STEPS, o); }
  };

  // Kuramoto: tiles revolve about the centre at individual speeds; past the critical coupling they lock into a spoke
  var KU_STEPS = 28;
  FX.kuramoto = {
    w: [2800, 600, 2600],
    prep: function (E) {
      var cx = E.W / 2, cy = E.H / 2, gam = 0.5, w0 = 0.8, dt = 0.22;
      eachPath(E, KU_STEPS, function (q, path) {
        var dx = q.tx - cx, dy = q.ty - cy, r = Math.sqrt(dx * dx + dy * dy), th = Math.atan2(dy, dx);
        var om = w0 + clamp(gam * Math.tan(Math.PI * (Math.random() - 0.5) * 0.98), -6, 6);
        for (var s = 0; s < KU_STEPS; s++) {
          path[s * 2] = cx + r * Math.cos(th); path[s * 2 + 1] = cy + r * Math.sin(th);
          var t = s * dt, K = 0.25 + 2.15 * Math.min(1, Math.max(0, (t - 0.8) / 5.7)), rr = K > 2 * gam ? Math.sqrt(1 - 2 * gam / K) : 0;
          for (var k = 0; k < 2; k++) th += (om + K * Math.max(rr, 0.03) * Math.sin(w0 * t - th)) * dt * 0.5 * 1.6;
        }
        path[0] = q.tx; path[1] = q.ty;
      });
    },
    at: function (q, u, ui, E, o) { pathAt(q, ui, KU_STEPS, o); }
  };

  // Chladni: sand slides to the nodal lines of cos(n pi x) cos(m pi y) - cos(m pi x) cos(n pi y)
  var CH_STEPS = 14;
  FX.chladni = {
    w: [2300, 900, 2300],
    prep: function (E) {
      var n = 3, m = 8, pi = Math.PI;
      eachPath(E, CH_STEPS, function (q, path) {
        var u = q.tx / E.W, v = q.ty / E.H;
        for (var s = 0; s < CH_STEPS; s++) {
          path[s * 2] = u * E.W; path[s * 2 + 1] = v * E.H;
          var w = Math.cos(n * pi * u) * Math.cos(m * pi * v) - Math.cos(m * pi * u) * Math.cos(n * pi * v);
          var gx = -n * pi * Math.sin(n * pi * u) * Math.cos(m * pi * v) + m * pi * Math.sin(m * pi * u) * Math.cos(n * pi * v);
          var gy = -m * pi * Math.cos(n * pi * u) * Math.sin(m * pi * v) + n * pi * Math.cos(m * pi * u) * Math.sin(n * pi * v);
          var g2 = gx * gx + gy * gy + 0.5;
          u = clamp(u - 0.55 * w * gx / g2 + gaussian() * 0.0025, 0, 1); v = clamp(v - 0.55 * w * gy / g2 + gaussian() * 0.0025, 0, 1);
        }
      });
    },
    at: function (q, u, ui, E, o) { pathAt(q, ui, CH_STEPS, o); }
  };

  // Double slit: each tile passes one slit and lands where cos²(k_d y)·sinc²(k_a y) allows
  FX.doubleslit = {
    w: [2600, 800, 2400],
    prep: function (E) {
      var kd = Math.PI / 0.2, ka = Math.PI / 0.6;
      E.particles.forEach(function (q) {
        var yl = 0, tries = 0;
        for (; tries < 40; tries++) {
          var y = (Math.random() * 2 - 1) * 0.9, c = Math.cos(kd * y), sn = Math.abs(ka * y) < 1e-3 ? 1 : Math.sin(ka * y) / (ka * y);
          if (Math.random() < c * c * sn * sn) { yl = y; break; }
        }
        if (tries === 40) yl = Math.round((Math.random() * 2 - 1) * 4) * 0.2;
        q.slx = E.W * 0.46; q.sly = E.H * (0.5 + (Math.random() < 0.5 ? -1 : 1) * 0.05);
        q.ax = E.W * (0.78 + 0.18 * Math.random()) - E.cell; q.ay = (1 - yl) / 2 * E.H - E.cell / 2;   // a band, so each fringe is a bar
      });
    },
    at: function (q, u, ui, E, o) {
      if (ui < 0.4) { var a = ui / 0.4; o.x = q.tx + (q.slx - q.tx) * a; o.y = q.ty + (q.sly - q.ty) * a; }
      else { var b = (ui - 0.4) / 0.6; o.x = q.slx + (q.ax - q.slx) * b; o.y = q.sly + (q.ay - q.sly) * b; }
    }
  };

  // Cyclotron: gyration about a guiding centre plus the E x B drift (the same for either sign of charge); the tint marks the sign
  FX.cyclotron = {
    w: [2400, 700, 2400],
    prep: function (E) {
      E.particles.forEach(function (q) {
        q.rho = (0.03 + 0.07 * Math.random()) * E.W; q.phi = Math.random() * TAU; q.sgn = Math.random() < 0.5 ? 1 : -1;
        q.alt = E.mixLevels(q, q.sgn > 0 ? E.col.a : E.col.b);
      });
    },
    at: function (q, u, ui, E, o) {
      var ang = q.phi + q.sgn * TAU * 3 * ui;
      var x = q.tx + 0.34 * E.W * ui + q.rho * (Math.cos(ang) - Math.cos(q.phi));
      o.x = x - Math.floor(x / E.W) * E.W;                // the drift wraps around, so no tile is lost
      o.y = q.ty + q.rho * (Math.sin(ang) - Math.sin(q.phi));
      o.c = q.alt[Math.round(ui * 0.6 * (E.LEVELS - 1))];
    }
  };

  // Phyllotaxis: tiles take golden-angle seed positions, darkest at the centre
  FX.phyllotaxis = {
    w: [2400, 800, 2400],
    prep: function (E) {
      var order = byLuminance(E.particles), N = order.length, ga = 137.5077 * Math.PI / 180;
      order.forEach(function (idx, rank) {
        var q = E.particles[idx], r = Math.sqrt((rank + 0.5) / N), a = rank * ga;
        q.ax = E.W / 2 + Math.cos(a) * r * E.W * 0.47 - E.cell / 2; q.ay = E.H / 2 + Math.sin(a) * r * E.H * 0.47 - E.cell / 2;
      });
    },
    at: function (q, u, ui, E, o) { lerpTo(q, ui, o); }
  };

  // Lissajous: tiles line up along x = A sin(3t + d), y = B sin(2t), ordered by brightness
  FX.lissajous = {
    w: [2400, 800, 2400],
    prep: function (E) {
      var order = byLuminance(E.particles), N = order.length;
      order.forEach(function (idx, rank) {
        var q = E.particles[idx], s = rank / N * TAU;
        q.ax = E.W / 2 + Math.sin(3 * s + 0.6) * E.W * 0.46 - E.cell / 2; q.ay = E.H / 2 + Math.sin(2 * s) * E.H * 0.46 - E.cell / 2;
      });
    },
    at: function (q, u, ui, E, o) { lerpTo(q, ui, o); }
  };

  // Monte Carlo: tiles are thrown at random; those inside the inscribed ellipse turn madder, the rest indigo
  FX.montecarlo = {
    w: [2000, 1200, 2000],
    prep: function (E) {
      E.particles.forEach(function (q) {
        q.ax = Math.random() * (E.W - E.cell); q.ay = Math.random() * (E.H - E.cell);
        var dx = (q.ax + E.cell / 2) / E.W * 2 - 1, dy = (q.ay + E.cell / 2) / E.H * 2 - 1;
        q.alt = E.mixLevels(q, dx * dx + dy * dy < 1 ? E.col.a : E.col.b);
      });
    },
    at: function (q, u, ui, E, o) {
      lerpTo(q, ui, o);
      o.c = q.alt[Math.round(ui * (E.LEVELS - 1))];
    }
  };

  // Galaxy: flat rotation curve, Omega ~ 1/(r + r0); winds the portrait into arms and warms the core
  FX.galaxy = {
    w: [2800, 600, 2600],
    prep: function (E) {
      E.particles.forEach(function (q) { q.alt = E.mixLevels(q, E.col.o); });
    },
    at: function (q, u, ui, E, o) {
      var dx = (q.tx - E.W / 2) / (E.W / 2), dy = (q.ty - E.H / 2) / (E.H / 2), r = Math.sqrt(dx * dx + dy * dy);
      var ang = ui * 6.5 * 0.35 / (r + 0.16);
      var ca = Math.cos(ang), sa = Math.sin(ang);
      o.x = E.W / 2 + (dx * ca - dy * sa) * E.W / 2;
      o.y = E.H / 2 + (dx * sa + dy * ca) * E.H / 2;
      o.c = q.alt[Math.round(ui * clamp(1.3 - r, 0, 1) * (E.LEVELS - 1))];
    }
  };

  // Optimal transport: in each column the tiles are re-sorted by brightness (the monotone map between the column's
  // brightness distribution and a uniform one), moving in straight lines
  FX.transport = {
    w: [2400, 900, 2400],
    prep: function (E) {
      var cols = Math.round(E.W / E.cell), byCol = [], i;
      for (i = 0; i < cols; i++) byCol.push([]);
      E.particles.forEach(function (q) { byCol[Math.min(cols - 1, Math.round(q.tx / E.cell))].push(q); });
      byCol.forEach(function (col) {
        col.sort(function (p, q) { return p.lum - q.lum; });          // darkest first: they go to the top
        col.forEach(function (q, rank) { q.ax = q.tx; q.ay = rank * E.cell; });
      });
    },
    at: function (q, u, ui, E, o) { lerpTo(q, ui, o); }
  };

  // Brownian bridge: a random excursion that is pinned at both ends, B(s) = sum xi_k sqrt(2) sin(k pi s) / (k pi)
  var BB_STEPS = 20;
  FX.bridge = {
    w: [2600, 600, 2600],
    prep: function (E) {
      var K = 6, sx = E.W * 0.13, sy = E.H * 0.09;
      eachPath(E, BB_STEPS, function (q, path) {
        var xi = [], yi = [], k;
        for (k = 0; k < K; k++) { xi.push(gaussian()); yi.push(gaussian()); }
        for (var s = 0; s < BB_STEPS; s++) {
          var t = s / (BB_STEPS - 1) * 0.5, bx = 0, by = 0;
          for (k = 1; k <= K; k++) { var f = Math.SQRT2 * Math.sin(k * Math.PI * t) / (k * Math.PI); bx += xi[k - 1] * f; by += yi[k - 1] * f; }
          path[s * 2] = reflect(q.tx + sx * bx * 2, 0, E.W - E.cell); path[s * 2 + 1] = reflect(q.ty + sy * by * 2, 0, E.H - E.cell);
        }
      });
    },
    at: function (q, u, ui, E, o) { pathAt(q, ui, BB_STEPS, o); }
  };

  // Fountain: jets leave a nozzle at the bottom centre and land on the floor; each tile takes a seat on one of the parabolas
  FX.fountain = {
    w: [2000, 800, 2000],
    prep: function (E) {
      var J = 14, jets = [], k;
      for (k = 0; k < J; k++) {
        var d = ((k + 0.5) / J - 0.5) * 0.96 * E.W;
        jets.push({ d: d, h: (0.2 + 0.7 * (1 - Math.abs(d) / (0.52 * E.W))) * E.H });   // nearer jets rise higher
      }
      E.particles.forEach(function (q) {
        var j = jets[Math.floor(Math.random() * J)], s = Math.random();
        q.ax = E.W / 2 + j.d * s - E.cell / 2 + gaussian() * E.cell * 0.3;
        q.ay = E.H - E.cell - 4 * j.h * s * (1 - s);
      });
    },
    at: function (q, u, ui, E, o) { lerpTo(q, ui, o); }
  };

  // Zel'dovich approximation: x = q + D(t) psi(q) with psi = -grad(Phi), Phi a sum of plane waves
  FX.cosmicweb = {
    w: [2800, 700, 2600],
    prep: function (E) {
      var waves = [];
      for (var i = 0; i < 7; i++) {
        var ang = Math.random() * TAU, mag = 2.2 + 3 * Math.random();
        waves.push({ kx: Math.cos(ang) * mag, ky: Math.sin(ang) * mag, a: (0.5 + 0.5 * Math.random()) * 1.2 / (mag * mag), ph: Math.random() * TAU });
      }
      E.particles.forEach(function (q) {
        var x = nxOf(E, q), y = nyOf(E, q), px = 0, py = 0;
        for (var i = 0; i < waves.length; i++) { var w = waves[i], s = Math.sin(w.kx * x + w.ky * y + w.ph); px += w.a * w.kx * s; py += w.a * w.ky * s; }
        q.psx = px * E.W / 2; q.psy = -py * E.H / 2;
      });
    },
    at: function (q, u, ui, E, o) { o.x = q.tx + 1.5 * ui * q.psx; o.y = q.ty + 1.5 * ui * q.psy; }
  };
})();
